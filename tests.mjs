assert.equal(steps.filter(s=>s.phase==='pinyin').length,1);
assert.equal(steps.filter(s=>s.type==='wait'&&s.duration===8000).length,1);
const all=buildSessionSteps(words,{...initial.settings,repetitions:2,repeatGap:2,wordGap:8});
assert.deepEqual(all.slice(0,2).map(x=>[x.type,x.phase]),[['jingle','intro'],['say','intro']]);
assert.deepEqual(all.slice(-2).map(x=>[x.type,x.phase]),[['jingle','outro'],['say','outro']]);
assert.equal(all.filter(x=>x.phase==='word').length,4);
assert.equal(all[1].text,'准备好了吗？现在开始听写。');
assert.equal(all.at(-1).text,'本次听写已完成。辛苦了！');
const none=buildSessionSteps(words,{...initial.settings,introCue:false,outroCue:false});
assert.equal(none.length,buildSteps(words,initial.settings).length);
assert.equal(buildSessionSteps([],{...initial.settings}).length,0);
